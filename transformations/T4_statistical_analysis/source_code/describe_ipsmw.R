# ---------------------------------------------------------------
# Step: describe_ipsmw
#
# Input:
#   D4_StudyCohortCovariatesMain/Supplementary.parquet
#   D4_StudyCohort_IPSMW_Main/Supplementary.parquet
#   D5_PS_Coef_IPSMW_Main/Supplementary.csv
#
# Output:
#   D5_ASD_PREWEIGHT_IPSMW_Main/Supplementary.csv
#   D5_ASD_POSTWEIGHT_IPSMW_Main/Supplementary.csv
#   Figure3_IPSMW_Main/Supplementary.png
#   D5_weight_description_IPSMW_Main/Supplementary.csv
#   D5_exp_estimate_table_IPSMW_Main/Supplementary.csv
#   D5_Table4_IPSMW_Main/Supplementary.csv
#   D6_report/PSM_density_plot_Main/Supplementary.png
#   D6_report/PSM_histogram_plot_Main/Supplementary.png
# ---------------------------------------------------------------

if (
  !base::exists("lm", inherits = TRUE) ||
    !base::inherits(lm, "LoggerManager")
) {
  lm <- NULL
}
if (!base::is.null(lm)) {
  lm$start_script("describe_ipsmw.R")
  lm$start_capturing_prints()
}

# Load configuration utilities (I/O and YAML normalization).
source(file.path(
  "transformations",
  "T4_statistical_analysis",
  "source_code",
  "functions",
  "fn_config_utilities.R"
))

# Load weights and diagnostic functions (ASD, Table 4, visualizations).
source(file.path(
  "transformations",
  "T4_statistical_analysis",
  "source_code",
  "functions",
  "fn_weights_diagnostics.R"
))

# Load project configuration which specifies analyses and estimands.
config_project <- picard::load_config("configuration/config_project.yaml")
deap_name <- config_project$DEAP_configuration$name
compute_ipsmw_config <- config_project$compute_ipsmw

## Audit setup ---
picard::audit_start(
  file_name = "describe_ipsmw",
  deap_name = deap_name
)
logger::log_info("Start of the describe_ipsmw script.")
simulate_d4_config <- config_project$simulate_d4_data
metadata_file <- compute_ipsmw_config$metadata$ipsmw_variables_file
ipsmw_metadata <- data.table::fread(metadata_file)

# Validate selected analyses against allowed values (Main or Supplementary).
selected_analyses <- normalize_vec_config(compute_ipsmw_config$analyses)
allowed_analyses <- c("Main", "Supplementary")
invalid_analyses <- setdiff(selected_analyses, allowed_analyses)
if (length(invalid_analyses) > 0) {
  stop(paste0("Invalid analyses value(s): ", paste(invalid_analyses, collapse = ", "), "."))
}

# SAP requirement: IPSMW diagnostics must be for estimand 2 only.
selected_estimands <- as.integer(normalize_vec_config(compute_ipsmw_config$estimands))
if (length(selected_estimands) != 1L || selected_estimands[1] != 2L) {
  stop("describe_ipsmw must be configured with estimands: [2] (SAP requirement).")
}

# Set input/output directories pointing to compute_ipsmw outputs.
input_dir_d4 <- compute_ipsmw_config$output$dir_d4
input_dir_d5 <- compute_ipsmw_config$output$dir_d5
output_dir_d5 <- compute_ipsmw_config$output$dir_d5
covariates_file_template <- simulate_d4_config$output$covariates_file
metadata_files <- unlist(simulate_d4_config$metadata, use.names = FALSE)
ipsmw_weight <- compute_ipsmw_config$ipsmw_weight

# Run diagnostics for configured analyses (estimand 2 only).
for (analysis_label in selected_analyses) {
  logger::log_info(paste("Describing IPSMW for", analysis_label))

  # Check if required input files exist before attempting to load.
  d4_ipsmw_file <- paste0("D4_StudyCohort_IPSMW_", analysis_label, ".parquet")
  d4_ipsmw_all_file <- paste0("D4_StudyCohort_IPSMW_ALL_", analysis_label, ".parquet")
  d5_ps_coef_file <- paste0("D5_PS_Coef_IPSMW_", analysis_label, ".csv")
  d5_model_building_file <- paste0("D5_PS_ModelBuilding_IPSMW_", analysis_label, ".csv")

  # Check if main IPSMW dataset exists; if not, skip this analysis.
  ipsmw_file_path <- file.path(input_dir_d4, d4_ipsmw_file)
  if (!file.exists(ipsmw_file_path)) {
    logger::log_warn(paste(
      "Skipping IPSMW diagnostics for",
      analysis_label,
      "| Missing input file:",
      d4_ipsmw_file,
      "(compute_ipsmw may have failed for this analysis)"
    ))
    next
  }

  # Read IPSMW outputs generated by compute_ipsmw.R.
  d4_ipsmw <- picard::load(
    input_dir_d4,
    d4_ipsmw_file
  )

  # Load IPSMW_ALL if available (includes all exposed, not just compliant).
  ipsmw_all_file_path <- file.path(input_dir_d4, d4_ipsmw_all_file)
  if (file.exists(ipsmw_all_file_path)) {
    d4_ipsmw_all <- picard::load(
      input_dir_d4,
      d4_ipsmw_all_file
    )
  } else {
    logger::log_warn(paste(
      "D4_StudyCohort_IPSMW_ALL not found for",
      analysis_label,
      "- figures will not include all exposed"
    ))
    d4_ipsmw_all <- NULL
  }

  d5_ps_coef <- picard::load(
    input_dir_d5,
    d5_ps_coef_file
  )

  d5_model_building <- data.table::as.data.table(picard::load(
    input_dir_d5,
    d5_model_building_file
  ))

  # Reconstruct the exposed modeling source for prevalence in Table 4.
  cohort_file <- gsub(
    "{analysis}",
    analysis_label,
    compute_ipsmw_config$input$cohort_file,
    fixed = TRUE
  )
  fup_file <- gsub(
    "{analysis}",
    analysis_label,
    compute_ipsmw_config$input$fup_file,
    fixed = TRUE
  )
  cov_file <- gsub(
    "{analysis}",
    analysis_label,
    compute_ipsmw_config$input$cov_file,
    fixed = TRUE
  )

  # Load cohort, follow-up, and covariate data
  d4_cohort <- data.table::as.data.table(picard::load(
    compute_ipsmw_config$input$dir_d4,
    cohort_file
  ))[group %in% c("EXPOSED", "CONTROL")]
  d4_fup <- data.table::as.data.table(picard::load(
    compute_ipsmw_config$input$dir_d4,
    fup_file
  ))[compliant_exposed == TRUE][group %in% c("EXPOSED", "CONTROL")]
  d4_cov <- data.table::as.data.table(picard::load(
    compute_ipsmw_config$input$dir_d4,
    cov_file
  ))[group %in% c("EXPOSED", "CONTROL")]

  # Keep only compliant cases
  d4_cohort <- data.table::merge.data.table(
    x = d4_cohort,
    y = d4_fup[, .(person_id, T0, match_id, compliant_exposed)],
    by = c("person_id", "T0", "match_id"),
    all.x = FALSE
  )
  d4_cov <- data.table::merge.data.table(
    x = d4_cov,
    y = d4_fup[, .(person_id, T0, match_id, compliant_exposed)],
    by = c("person_id", "T0", "match_id"),
    all.x = FALSE
  )

  # Compute ASD tables before and after weighting for top covariates in model
  pre_asd <- compute_covariate_asd_table(
    covariate_data = d4_cov,
    metadata_files = metadata_files
  )
  post_asd <- compute_covariate_asd_table(
    covariate_data = d4_cov,
    metadata_files = metadata_files,
    weight_data = d4_ipsmw,
    weight_col = ipsmw_weight
  )

  picard::save(
    data = pre_asd,
    file_path = output_dir_d5,
    file_name = paste0("D5_ASD_PREWEIGHT_IPSMW_", analysis_label, ".csv")
  )

  picard::save(
    data = post_asd,
    file_path = output_dir_d5,
    file_name = paste0("D5_ASD_POSTWEIGHT_IPSMW_", analysis_label, ".csv")
  )

  # Build Figure 3 comparing top ASD covariates before and after weighting
  fig3 <- build_asd_comparison_plot(pre_asd = pre_asd, post_asd = post_asd, top_n = 15L) +
    ggplot2::ggtitle(paste(deap_name, "Figure 3 IPSMW", analysis_label))

  ggplot2::ggsave(
    filename = paste0(deap_name, "_Figure3_IPSMW_", analysis_label, ".png"),
    path = output_dir_d5,
    plot = fig3,
    width = 16,
    height = 16,
    units = "cm",
    dpi = 300
  )

  # The principal stratum score model is fit on the exposed group, so we merge
  # back to get the modeling source for prevalence calculations in Table 4.
  # This is also the source for variable distributions in the exposed group
  # for Figure 4/5 PSM diagnostics.
  exposed_model_source <- base::merge(
    x = d4_cohort[group == "EXPOSED"],
    y = d4_fup[, .(person_id, T0, match_id, group, ie1_second_dose_target_exposed)],
    by = c("person_id", "T0", "match_id", "group"),
    all.x = TRUE
  )
  exposed_model_source <- exposed_model_source[!is.na(ie1_second_dose_target_exposed)]

  # Add cov_data$SV_CCI to cohort_data
  cols_to_keep <- intersect(
    names(d4_cov),
    d5_model_building[included_r2 == TRUE]$variable_id
  )
  cols_to_keep <- c("person_id", "T0", "match_id", setdiff(cols_to_keep, names(exposed_model_source)))
  exposed_model_source <- data.table::merge.data.table(
    exposed_model_source,
    d4_cov[, ..cols_to_keep, with = FALSE],
    by = c("person_id", "T0", "match_id"),
    all.x = TRUE,
    all.y = FALSE
  )

  # Principal stratum score diagnostics are meaningful for controls, where
  # scores are model-based predictions.
  plot_data_control <- data.table::copy(d4_ipsmw[group == "CONTROL"])

  if (!"psm_score" %in% names(plot_data_control)) {
    stop(paste0("Missing 'psm_score' in D4 IPSMW table for ", analysis_label, "."))
  }

  # Build explicit before/after truncation scores for facetted diagnostics.
  trunc_lo <- stats::quantile(plot_data_control$psm_score, probs = compute_ipsmw_config$truncation$q_lower, na.rm = TRUE)
  trunc_hi <- stats::quantile(plot_data_control$psm_score, probs = compute_ipsmw_config$truncation$q_upper, na.rm = TRUE)
  plot_data_control[, psm_score_trim := data.table::fifelse(
    psm_score < trunc_lo,
    trunc_lo,
    data.table::fifelse(psm_score > trunc_hi, trunc_hi, psm_score)
  )]

  # Original Figure 4: controls only
  plot_long <- data.table::rbindlist(list(
    plot_data_control[, .(psm_score = psm_score, truncation = "Before truncation")],
    plot_data_control[, .(psm_score = psm_score_trim, truncation = "After truncation")]
  ))
  plot_long[, truncation := factor(truncation, levels = c("Before truncation", "After truncation"))]

  # Create facetted density plot of principal stratum scores (controls only).
  fig_ps_density <- ggplot2::ggplot(plot_long, ggplot2::aes(x = psm_score)) +
    ggplot2::geom_density(
      color = "dodgerblue3",
      fill = "dodgerblue3",
      linewidth = 0.8,
      alpha = 0.1
    ) +
    ggplot2::facet_wrap(~truncation, scales = "free") +
    # ggplot2::scale_x_continuous(breaks = scales::pretty_breaks(n = 5)) +
    ggplot2::scale_x_continuous(
      breaks = function(x) {
        seq(x[1], x[2], length.out = 4)
      },
      labels = function(x) {
        round(seq(x[1], x[2], length.out = 4), 3)
      }
    ) +
    ggplot2::scale_y_continuous(breaks = scales::pretty_breaks(n = 5)) +
    ggplot2::theme_minimal() +
    ggplot2::theme(axis.text.y = ggplot2::element_text(angle = 0)) +
    ggplot2::labs(
      x = "Principal Stratum Score",
      y = "Density",
      title = paste("Principal Stratum Score Density (Controls) -", analysis_label)
    )

  # Save density figure into reporting folder.
  ggplot2::ggsave(
    filename = paste0(deap_name, "_Figure4_PSM_density_plot_", analysis_label, ".png"),
    path = output_dir_d5,
    plot = fig_ps_density,
    width = 18,
    height = 12,
    dpi = 300,
    units = "cm"
  )

  # Create facetted histogram of IPSMW weights
  # Original Figure 5: exposed with unit weight (1) and controls with actual weights
  # For exposed: use design-based unit weight (ipsmw_raw = 1, ipsmw_raw_trunc = 1)
  # For controls: use actual computed weights

  # Get exposed with unit weights from d4_ipsmw (compliant exposed only)
  exposed_unit_weight <- d4_ipsmw[group == "EXPOSED", .(ipsmw_raw, ipsmw_raw_trunc)]
  if (nrow(exposed_unit_weight) == 0) {
    # If no compliant exposed in original d4_ipsmw, create dummy rows with weight 1
    exposed_unit_weight <- data.table::data.table(
      ipsmw_raw = rep(1, nrow(d4_ipsmw[group == "CONTROL"])),
      ipsmw_raw_trunc = rep(1, nrow(d4_ipsmw[group == "CONTROL"]))
    )
  }

  plot_long_hist <- data.table::rbindlist(list(
    plot_data_control[, .(ipsmw_weight_val = ipsmw_raw, truncation = "Before truncation", group_label = "Control")],
    plot_data_control[, .(ipsmw_weight_val = ipsmw_raw_trunc, truncation = "After truncation", group_label = "Control")],
    d4_ipsmw[group == "EXPOSED", .(ipsmw_weight_val = ipsmw_raw, truncation = "Before truncation", group_label = "Exposed")],
    d4_ipsmw[group == "EXPOSED", .(ipsmw_weight_val = ipsmw_raw_trunc, truncation = "After truncation", group_label = "Exposed")]
  ))

  plot_long_hist[, truncation := factor(truncation, levels = c("Before truncation", "After truncation"))]

  fig_ps_hist <- ggplot2::ggplot(plot_long_hist, ggplot2::aes(x = ipsmw_weight_val, color = group_label, fill = group_label)) +
    ggplot2::geom_histogram(
      alpha = 0.5,
      bins = 50
    ) +
    ggplot2::scale_color_manual(values = c("Control" = "dodgerblue3", "Exposed" = "red")) +
    ggplot2::scale_fill_manual(values = c("Control" = "dodgerblue3", "Exposed" = "red")) +
    ggplot2::facet_wrap(~truncation, scales = "free") +
    ggplot2::theme_minimal() +
    ggplot2::theme(axis.text.y = ggplot2::element_text(angle = 0)) +
    ggplot2::labs(
      x = "IPSMW",
      y = "Count",
      color = "Group",
      fill = "Group",
      title = paste("IPSMW Histogram -", analysis_label)
    )

  # Save histogram as Figure 5.
  ggplot2::ggsave(
    filename = paste0(deap_name, "_Figure5_IPSMW_histogram_plot_", analysis_label, ".png"),
    path = output_dir_d5,
    plot = fig_ps_hist,
    width = 18,
    height = 12,
    dpi = 300,
    units = "cm"
  )

  # Create exposed-weighted versions of figures if IPSMW_ALL is available
  if (!is.null(d4_ipsmw_all) && compute_ipsmw_config$weighted_exposed_figures) {
    # Figure 4 exposed-weighted: controls AND all exposed (all)
    plot_data_exposed_all <- data.table::copy(d4_ipsmw_all[group == "EXPOSED"])
    plot_data_exposed_all[, psm_score_trim := data.table::fifelse(
      psm_score < trunc_lo,
      trunc_lo,
      data.table::fifelse(psm_score > trunc_hi, trunc_hi, psm_score)
    )]

    plot_long_both <- data.table::rbindlist(list(
      plot_data_control[, .(psm_score = psm_score, truncation = "Before truncation", group_label = "Control")],
      plot_data_control[, .(psm_score = psm_score_trim, truncation = "After truncation", group_label = "Control")],
      plot_data_exposed_all[, .(psm_score = psm_score, truncation = "Before truncation", group_label = "Exposed (all)")],
      plot_data_exposed_all[, .(psm_score = psm_score_trim, truncation = "After truncation", group_label = "Exposed (all)")]
    ))
    plot_long_both[, truncation := factor(truncation, levels = c("Before truncation", "After truncation"))]

    fig_ps_density_exposed <- ggplot2::ggplot(plot_long_both, ggplot2::aes(x = psm_score, color = group_label, fill = group_label)) +
      ggplot2::geom_density(
        linewidth = 0.8,
        alpha = 0.1
      ) +
      ggplot2::scale_color_manual(values = c("Control" = "dodgerblue3", "Exposed (all)" = "red")) +
      ggplot2::scale_fill_manual(values = c("Control" = "dodgerblue3", "Exposed (all)" = "red")) +
      ggplot2::facet_wrap(~truncation, scales = "free") +
      # ggplot2::scale_x_continuous(breaks = scales::pretty_breaks(n = 5)) +
      ggplot2::scale_x_continuous(
        breaks = function(x) {
          seq(x[1], x[2], length.out = 4)
        },
        labels = function(x) {
          round(seq(x[1], x[2], length.out = 4), 3)
        }
      ) +
      ggplot2::scale_y_continuous(breaks = scales::pretty_breaks(n = 5)) +
      ggplot2::theme_minimal() +
      ggplot2::theme(axis.text.y = ggplot2::element_text(angle = 0)) +
      ggplot2::labs(
        x = "Principal Stratum Score",
        y = "Density",
        color = "Group",
        fill = "Group",
        title = paste("Principal Stratum Score Density (Controls + Exposed All) -", analysis_label)
      )

    ggplot2::ggsave(
      filename = paste0(deap_name, "_Figure4_PSM_density_plot_exposed_weighted_", analysis_label, ".png"),
      path = output_dir_d5,
      plot = fig_ps_density_exposed,
      width = 18,
      height = 12,
      dpi = 300,
      units = "cm"
    )

    # Figure 5 exposed-weighted: controls AND all exposed (all) with actual computed weights
    plot_long_hist_both <- data.table::rbindlist(list(
      plot_data_control[, .(ipsmw_weight_val = ipsmw_raw, truncation = "Before truncation", group_label = "Control")],
      plot_data_control[, .(ipsmw_weight_val = ipsmw_raw_trunc, truncation = "After truncation", group_label = "Control")],
      plot_data_exposed_all[, .(ipsmw_weight_val = ipsmw_raw, truncation = "Before truncation", group_label = "Exposed (all)")],
      plot_data_exposed_all[, .(ipsmw_weight_val = ipsmw_raw_trunc, truncation = "After truncation", group_label = "Exposed (all)")]
    ))
    plot_long_hist_both[, truncation := factor(truncation, levels = c("Before truncation", "After truncation"))]

    fig_ps_hist_exposed <- ggplot2::ggplot(plot_long_hist_both, ggplot2::aes(x = ipsmw_weight_val, color = group_label, fill = group_label)) +
      ggplot2::geom_histogram(
        alpha = 0.5,
        bins = 50
      ) +
      ggplot2::scale_color_manual(values = c("Control" = "dodgerblue3", "Exposed (all)" = "red")) +
      ggplot2::scale_fill_manual(values = c("Control" = "dodgerblue3", "Exposed (all)" = "red")) +
      ggplot2::facet_wrap(~truncation, scales = "free") +
      ggplot2::theme_minimal() +
      ggplot2::theme(axis.text.y = ggplot2::element_text(angle = 0)) +
      ggplot2::labs(
        x = "IPSMW",
        y = "Count",
        color = "Group",
        fill = "Group",
        title = paste("IPSMW Histogram (Controls + Exposed All) -", analysis_label)
      )

    ggplot2::ggsave(
      filename = paste0(deap_name, "_Figure5_IPSMW_histogram_plot_exposed_weighted_", analysis_label, ".png"),
      path = output_dir_d5,
      plot = fig_ps_hist_exposed,
      width = 18,
      height = 12,
      dpi = 300,
      units = "cm"
    )
  }

  # Summarize weight distribution by group (using non-truncated weights)
  weight_table <- describe_iptw(
    p_matrix = d4_ipsmw,
    groups = c("CONTROL", "EXPOSED"),
    weight_col = "ipsmw_raw",
    custom_truncation = c(
      compute_ipsmw_config$truncation$q_lower,
      compute_ipsmw_config$truncation$q_upper
    ),
    digits = 4
  )

  weight_table$analysis <- analysis_label

  # Persist weight diagnostics table.
  picard::save(
    data = weight_table,
    file_path = output_dir_d5,
    file_name = paste0(deap_name, "_Table5_D5_weight_description_IPSMW_", analysis_label, ".csv")
  )

  # Create OR + CI presentation table from model coefficients.
  exp_estimate_table <- data.table::as.data.table(
    d5_ps_coef[coefficient != "(Intercept)"]
  )

  # Compute 95% confidence interval bounds for exponentiated coefficients.
  exp_estimate_table[, exp_estimate_lower := exp(estimate + qnorm(0.025) * std_error)]
  exp_estimate_table[, exp_estimate_upper := exp(estimate + qnorm(0.975) * std_error)]
  exp_estimate_table[, OR_ci := paste0(
    round(exp_estimate, 2),
    " (",
    round(exp_estimate_lower, 2),
    "-",
    round(exp_estimate_upper, 2),
    ")"
  )]

  # Persist coefficient summary table for reports.
  picard::save(
    data = exp_estimate_table,
    file_path = output_dir_d5,
    file_name = paste0("D5_exp_estimate_table_IPSMW_", analysis_label, ".csv")
  )

  # Build Table 4 content by combining prevalence with final-model ORs.
  table4_vars <- base::merge(
    x = d5_model_building[included_r2 == TRUE, .(variable_id)],
    y = ipsmw_metadata[, .(variable_id = var, label)],
    by = "variable_id",
    all.x = TRUE
  )
  table4_vars <- unique(table4_vars)
  table4_vars[, variable_in_data := variable_id]
  table4_vars[, source_name := "BASELINE"]

  table4_ipsmw <- build_table4_prevalence_or(
    variable_map = table4_vars,
    coef_table = exp_estimate_table,
    source_lookup = list(BASELINE = exposed_model_source),
    prevalence_digits = 1,
    or_digits = 2
  )
  table4_ipsmw$analysis <- analysis_label
  table4_ipsmw$estimand <- 2L

  picard::save(
    data = table4_ipsmw,
    file_path = output_dir_d5,
    file_name = paste0(deap_name, "_Table4_D5_IPSMW_", analysis_label, ".csv")
  )
}

# Clean the environment
objects_to_remove <- c(
  "d4_ipsmw", "d4_ipsmw_all", "d5_ps_coef", "d5_model_building",
  "d4_cohort", "d4_fup", "cohort_file", "fup_file",
  "d4_cov", "pre_asd", "post_asd", "fig3",
  "exposed_model_source", "plot_data_control", "plot_data_exposed_all",
  "exposed_unit_weight", "plot_long_both", "plot_long_hist_both",
  "trunc_lo", "trunc_hi", "plot_long", "plot_long_hist",
  "fig_ps_density", "fig_ps_hist",
  "fig_ps_density_exposed", "fig_ps_hist_exposed",
  "weight_table", "exp_estimate_table",
  "table4_vars", "table4_ipsmw",
  "analysis_label", "ipsmw_metadata", "selected_analyses"
)

rm(list = intersect(objects_to_remove, ls()))
gc()

# Close logs
picard::audit_end()

if (!base::is.null(lm)) {
  lm$stop_capturing_prints()
  lm$end_script()
}

logger::log_info("End of the describe_ipsmw script.")
